/**
 * Inline the production client build into `server/generated/client-assets.js`
 * so the packaged application can serve the UI from inside the executable.
 *
 * Usage: node scripts/embed-client.mjs   (run `npm run build:client` first)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(root, 'dist');
const outFile = path.join(root, 'server', 'generated', 'client-assets.js');

const CONTENT_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.gif': 'image/gif',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.txt': 'text/plain; charset=utf-8',
};

function walk(dir, prefix = '') {
  const entries = [];
  for (const item of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, item.name);
    const url = `${prefix}/${item.name}`;
    if (item.isDirectory()) entries.push(...walk(full, url));
    else if (item.isFile()) entries.push({ url, full });
  }
  return entries;
}

if (!fs.existsSync(distDir)) {
  console.error('No client build found. Run `npm run build:client` before embedding.');
  process.exit(1);
}

const files = walk(distDir);
if (!files.length) {
  console.error('The client build is empty. Run `npm run build:client` again.');
  process.exit(1);
}

const assets = {};
let bytes = 0;
for (const file of files) {
  const buffer = fs.readFileSync(file.full);
  bytes += buffer.length;
  assets[file.url] = {
    type: CONTENT_TYPES[path.extname(file.url).toLowerCase()] || 'application/octet-stream',
    body: buffer.toString('base64'),
  };
}

if (!assets['/index.html']) {
  console.error('The client build has no index.html at its root.');
  process.exit(1);
}

const banner = [
  '/*',
  ' * Generated by scripts/embed-client.mjs - do not edit.',
  ` * ${files.length} file(s) from dist/, ${(bytes / 1024).toFixed(1)} kB inlined as base64.`,
  ' */',
  '',
].join('\n');

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${banner}export const CLIENT_ASSETS = ${JSON.stringify(assets)};\n`, 'utf8');

console.log(
  `Embedded ${files.length} client file(s) (${(bytes / 1024).toFixed(1)} kB) into ${path.relative(root, outFile)}`
);
