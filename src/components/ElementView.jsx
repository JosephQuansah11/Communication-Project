function gradientDefs(fill, id) {
  if (typeof fill !== 'string' || !fill.startsWith('linear-gradient')) return null;
  const colors = fill.match(/#(?:[0-9a-f]{3,8})|rgba?\([^)]*\)/gi) || [];
  if (colors.length < 2) return null;
  return (
    <defs>
      <linearGradient id={id} x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stopColor={colors[0]} />
        <stop offset="100%" stopColor={colors[colors.length - 1]} />
      </linearGradient>
    </defs>
  );
}

/**
 * A picture fill inside a shape is an SVG `<pattern>` holding the image, so the
 * picture is clipped to the exact outline of the shape (rect, ellipse, star…).
 */
function pictureDef(picture, id) {
  const { patternWidth, patternHeight, preserveAspectRatio } = picturePatternLayout(picture.fit);
  return (
    <defs>
      <pattern
        id={id}
        patternUnits="objectBoundingBox"
        patternContentUnits="objectBoundingBox"
        width={patternWidth}
        height={patternHeight}
      >
        <image
          href={picture.src}
          x="0"
          y="0"
          width="1"
          height="1"
          opacity={picture.opacity}
          preserveAspectRatio={preserveAspectRatio}
        />
      </pattern>
    </defs>
  );
}

/**
 * The outline of a shape, drawn from its rings: a rectangle with an independent
 * radius per corner, a preset polygon (optionally with rounded corners) or a
 * custom path. `fillRule="evenodd"` is what turns a boolean result into a shape
 * with real holes in it.
 */
/**
 * Whether the reader is happy for things to move.
 *
 * The shape wobble and the motion scenes both ask this: `prefers-reduced-motion` is a
 * request, and honouring it is the difference between a nice effect and an unpleasant one.
 */
export function motionAllowed() {
  if (typeof window === 'undefined' || !window.matchMedia) return true;
  return !window.matchMedia('(prefers-reduced-motion: reduce)').matches;
}

/**
 * Renders a shape.
 *
 * A blob — the water drop — has elliptical corners of its own (`blobRings`), can breathe
 * between the drop and a circle, and carries a water shine; everything else is drawn from
 * its point table, a radius or a custom path. The text a shape holds is clipped to the
 * same outline, so words sit *inside* the drop rather than spilling out of it.
 */
export function ShapeArt({ element, preview = false }) {
  const w = Math.max(1, Number(element.w) || 100);
  const h = Math.max(1, Number(element.h) || 100);
  const rings = shapeLocalRings(element);
  const d = ringsToD(rings);
  const open = rings.some((ring) => ring.closed === false);
  const safeId = String(element.id || 'shape').replace(/[^a-zA-Z0-9_-]/g, '');
  const gradientId = `grad-${safeId}`;
  const pictureId = `pic-${safeId}`;
  const picture = normalizePictureFill(element.fillImage);
  const gradient = picture ? null : gradientDefs(element.fill, gradientId);
  const solid = picture
    ? `url(#${pictureId})`
    : gradient
      ? `url(#${gradientId})`
      : element.fill === 'transparent'
        ? 'none'
        : element.fill;
  // An open path is a line, so it borrows the fill colour as its ink.
  const ink = element.stroke || (open && element.fill !== 'transparent' ? element.fill : null);
  const strokeProps = ink
    ? { stroke: ink, strokeWidth: Math.max(0.5, Number(element.strokeWidth) || 1), vectorEffect: 'non-scaling-stroke' }
    : {};
  /**
   * A blob can breathe: the outline is morphed between the drop and a circle with SMIL,
   * which needs no frame loop and no state — the two paths are generated by the same
   * function, so they have the same commands and the browser can interpolate them. A
   * thumbnail, a reader who asked for less movement, or a shape with the wobble switched
   * off simply gets the still outline.
   */
  const blob = shapeBlob(element.shape);
  const wobble = blob && element.wobble !== false && !preview && motionAllowed();
  const wobbleD = wobble ? ringsToD(blobRings(0, 0, w, h, blobRadii(blob, WATER_DROP_ROUND, 1))) : null;
  // A drop shines: two soft highlights on the shoulder, the way water catches the light.
  const shine = blob && element.shine !== false && !picture && element.fill !== 'transparent';

  return (
    <svg
      viewBox={`0 0 ${w} ${h}`}
      preserveAspectRatio="none"
      width="100%"
      height="100%"
      style={{ display: 'block', pointerEvents: 'none' }}
    >
      {picture ? pictureDef(picture, pictureId) : gradient}
      <path d={d} fill={open ? 'none' : solid} fillRule="evenodd" {...strokeProps}>
        {wobbleD ? (
          <animate
            attributeName="d"
            values={`${d};${wobbleD};${d}`}
            keyTimes="0;0.5;1"
            dur="6s"
            calcMode="spline"
            keySplines="0.42 0 0.58 1;0.42 0 0.58 1"
            repeatCount="indefinite"
          />
        ) : null}
      </path>
      {shine ? (
        <g className="shape-shine">
          <ellipse cx={w * 0.24} cy={h * 0.2} rx={w * 0.1} ry={h * 0.072} />
          <ellipse cx={w * 0.34} cy={h * 0.31} rx={w * 0.042} ry={h * 0.03} />
        </g>
      ) : null}
    </svg>
  );
}

function RichText({ element, characters }) {
  if (!element.runs?.length) return element.text;
  const joined = element.runs.map((run) => run.text).join('');
  if (joined !== element.text) return element.text;
  let offset = 0;
  return element.runs.map((run, index) => {
    const scripted = run.superscript || run.subscript;
    const start = offset;
    offset += String(run.text || '').length;
    return (
      <span
        key={index}
        style={{
          fontFamily: run.fontFamily ? fontStack(run.fontFamily) : undefined,
          fontSize: scripted ? '0.72em' : run.fontSize ? `${run.fontSize}px` : undefined,
          color: run.color || undefined,
          background: run.highlight || undefined,
          fontWeight: run.bold ? 700 : undefined,
          fontStyle: run.italic ? 'italic' : undefined,
          textDecoration: run.underline ? 'underline' : undefined,
          verticalAlign: run.superscript ? 'super' : run.subscript ? 'sub' : undefined,
          whiteSpace: 'pre-wrap',
        }}
      >
        {characters ? splitCharacters(run.text).map((character, position) => characterSpan(character, characters, start + position)) : run.text}
      </span>
    );
  });
}

/**
 * One character of a per-character animation. The character's own place in the text
 * decides its delay, so a run of styled text waves in the same order as plain text.
 */
function characterSpan(character, characters, index) {
  return (
    <span key={index} className="anim-char" style={characterStyle(characters.animation, index, characters.count, characters.played)}>
      {character}
    </span>
  );
}

/**
 * Renders a text box body: formatted HTML when the box carries it, otherwise the
 * imported runs, otherwise plain text. A `style`-level highlight/script wraps
 * the plain fallback so box-level formatting still shows.
 *
 * `characters` is set when the box is animating one character at a time; rich HTML
 * cannot be split without breaking its markup, so those boxes animate as a whole.
 */
function RichContent({ element, characters }) {
  const style = element.style || {};
  const scripted = style.superscript || style.subscript;
  const html = sanitizeHtml(textElementHtml(element));
  if (hasRichHtml(html)) {
    return <div className="rich-text" dangerouslySetInnerHTML={{ __html: html }} />;
  }
  if (element.runs?.length) return <RichText element={element} characters={characters} />;
  const highlight = style.highlight || undefined;
  if (characters) {
    return splitCharacters(element.text).map((character, index) => characterSpan(character, characters, index));
  }
  if (!highlight && !scripted) return element.text;
  return (
    <span
      style={{
        background: highlight,
        verticalAlign: style.superscript ? 'super' : style.subscript ? 'sub' : undefined,
        fontSize: scripted ? '0.72em' : undefined,
      }}
    >
      {element.text}
    </span>
  );
}

/**
 * The padding of a text body: the per-side insets the file declared when it has
 * them (PowerPoint's own `lIns/tIns/rIns/bIns`), otherwise the single padding the
 * editor's controls work with.
 */
function elementPadding(element, fallback) {
  const insets = element?.paddingInsets;
  if (insets && ['top', 'right', 'bottom', 'left'].every((side) => Number.isFinite(insets[side]))) {
    return `${insets.top}px ${insets.right}px ${insets.bottom}px ${insets.left}px`;
  }
  return `${element?.padding ?? fallback}px`;
}

/**
 * An online video (a YouTube or Vimeo link) plays through the provider's own
 * player. It starts paused behind its poster frame — one click plays it — so a
 * show never bursts into sound on its own, and the editor stays calm.
 */
function OnlineVideo({ element, playing, onPlay, style }) {
  const video = parseOnlineVideo(element.src);
  const poster = element.poster || video?.thumbnailUrl || null;
  if (playing) {
    return (
      <iframe
        className="online-video-frame"
        src={onlineVideoEmbedUrl(video, { autoplay: true, start: element.startAt || null })}
        title={element.name || 'Online video'}
        allow="autoplay; encrypted-media; picture-in-picture; fullscreen"
        allowFullScreen
        referrerPolicy="strict-origin-when-cross-origin"
        style={{ width: '100%', height: '100%', border: 0, display: 'block', ...style }}
      />
    );
  }
  return (
    <button
      type="button"
      className="online-video-poster"
      style={{ ...style, width: '100%', height: '100%', border: 0, padding: 0, cursor: 'pointer', position: 'relative' }}
      onClick={(event) => {
        event.stopPropagation();
        onPlay();
      }}
      title="Play this video"
    >
      {poster ? (
        <img src={poster} alt="" draggable={false} style={{ width: '100%', height: '100%', objectFit: 'cover', display: 'block' }} />
      ) : (
        <span className="online-video-poster-fallback" />
      )}
      <span className="video-play-badge">
        <Icon name="play" size={26} filled />
      </span>
      <span className="video-preview-name">{element.name || 'Online video'}</span>
    </button>
  );
}

function MediaExpandButton({ onClick, label = 'Expand' }) {
  return (
    <button
      type="button"
      className="media-expand-btn"
      title={label}
      onPointerDown={(event) => event.stopPropagation()}
      onClick={(event) => {
        event.stopPropagation();
        onClick?.();
      }}
    >
      <Icon name="expand" size={18} />
    </button>
  );
}

export default function ElementView({
  element,
  editingText = false,
  onTextCommit,
  onMediaExpand,
  mediaInteractive = false,
  preview = false,
  onTableDoubleClick,
  tableHighlight,
  editorRef,
  animations,
  animStep,
  slideSize,
}) {
  const textAreaRef = useRef(null);
  /** True once the viewer started an online video on this slide. */
  const [onlinePlaying, setOnlinePlaying] = useState(false);

  useEffect(() => {
    if (!editingText) return;
    const node = textAreaRef.current;
    if (!node) return;
    // Seed the contenteditable once per edit session: React must not own the
    // children or it would reset the caret on every render.
    node.innerHTML = textElementHtml(element);
    node.focus();
    const range = document.createRange();
    range.selectNodeContents(node);
    range.collapse(false);
    const selection = window.getSelection();
    selection?.removeAllRanges();
    selection?.addRange(range);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [editingText, element.id]);

  const commitText = (options) => {
    const node = textAreaRef.current;
    if (!node) {
      onTextCommit?.({ text: '', html: '' }, options);
      return;
    }
    const html = sanitizeHtml(node.innerHTML);
    onTextCommit?.({ html, text: htmlToPlainText(html) }, options);
  };

  // An imported (or authored) effect is applied to the element root. `animStep`
  // is the number of click steps that have played; null means "show everything"
  // (the editor, thumbnails and any deck without animations).
  const resolvedAnimation =
    typeof animStep === 'number' && animations?.length
      ? resolveElementAnimation(animations, element.id, animStep)
      : null;
  /**
   * A per-character effect (Dynamic) belongs to the characters, not to the box, so
   * the box must not animate as well. Rich HTML cannot be split without breaking its
   * markup, so a box carrying it falls back to animating as a whole.
   */
  const characterCount =
    element.type === 'text'
      ? splitCharacters(element.runs?.length ? element.runs.map((run) => run.text).join('') : element.text).length
      : 0;
  const perCharacter =
    Boolean(resolvedAnimation) &&
    isPerCharacter(resolvedAnimation.animation) &&
    characterCount > 0 &&
    !hasRichHtml(sanitizeHtml(textElementHtml(element)));
  const characterAnimation = perCharacter
    ? { animation: resolvedAnimation.animation, played: resolvedAnimation.played, count: characterCount }
    : null;
  const animationStyles = perCharacter ? null : animationStyle(resolvedAnimation, slideSize) || null;
  const animationClass = resolvedAnimation ? ' slide-animated' : '';

  const baseStyle = {
    position: 'absolute',
    left: `${element.x}px`,
    top: `${element.y}px`,
    width: `${element.w}px`,
    height: `${element.h}px`,
    transform: element.rotation ? `rotate(${element.rotation}deg)` : undefined,
    opacity: element.opacity ?? 1,
    ...animationStyles,
  };

  if (element.type === 'shape') {
    const style = element.style || {};
    const blob = shapeBlob(element.shape);
    const hasText = Boolean(element.text || element.html);
    const textWobble = blob && element.wobble !== false && !preview && motionAllowed();
    return (
      <div className={`element element-shape${animationClass}`} style={baseStyle}>
        <ShapeArt element={element} preview={preview} />
        {hasText ? (
          /**
           * The text rides inside the outline: a blob's box is clipped with a
           * `border-radius` (the same numbers the outline is drawn from), and it breathes
           * on the same 6-second loop as the shape itself, so the words stay in the water.
           */
          <div
            className={`shape-clip${blob ? ' shape-clip-blob' : ''}`}
            style={{
              position: 'absolute',
              inset: 0,
              overflow: 'hidden',
              ...(blob ? { borderRadius: blobCss(blob), animation: textWobble ? 'drop-wobble 6s infinite' : undefined } : null),
            }}
          >
            <div
              className="shape-text"
              style={{
                position: 'absolute',
                inset: 0,
                padding: elementPadding(element, 10),
                display: 'flex',
                alignItems: style.valign === 'top' ? 'flex-start' : style.valign === 'bottom' ? 'flex-end' : 'center',
                justifyContent:
                  style.align === 'left' ? 'flex-start' : style.align === 'right' ? 'flex-end' : 'center',
                fontFamily: fontStack(style.fontFamily),
                fontSize: `${style.fontSize || 24}px`,
                color: style.color || '#ffffff',
                fontWeight: style.bold ? 700 : 500,
                fontStyle: style.italic ? 'italic' : 'normal',
                textAlign: style.align || 'center',
                lineHeight: style.lineHeight || 1.25,
                whiteSpace: 'pre-wrap',
                wordBreak: 'break-word',
                pointerEvents: 'none',
                overflow: 'hidden',
              }}
            >
              <RichContent element={element} />
            </div>
          </div>
        ) : null}
      </div>
    );
  }

  if (element.type === 'image') {
    const clipped = element.clipShape && element.clipShape !== 'none';
    const corners = element.corners;
    return (
      <div
        className={`element element-image ${element.expandable ? 'expandable' : ''}${animationClass}`}
        style={{
          ...baseStyle,
          overflow: 'hidden',
          clipPath: clipPathFor(element.clipShape) || undefined,
          // Per-corner radii win over the single radius, so the canvas rounding dots
          // can shape one corner of a picture at a time.
          borderRadius: clipped
            ? 0
            : corners
              ? `${corners.tl || 0}px ${corners.tr || 0}px ${corners.br || 0}px ${corners.bl || 0}px`
              : `${element.radius || 0}px`,
          border: element.stroke ? `${element.strokeWidth || 1}px solid ${element.stroke}` : 'none',
          boxSizing: 'border-box',
          cursor: element.expandable ? 'zoom-in' : undefined,
        }}
        onClick={(event) => {
          if (!element.expandable) return;
          event.stopPropagation();
          onMediaExpand?.(element);
        }}
      >
        <img
          src={element.src}
          alt={element.name || ''}
          draggable={false}
          style={{
            width: '100%',
            height: '100%',
            objectFit: element.fit || 'cover',
            transform: `translate(${element.crop?.x || 0}%, ${element.crop?.y || 0}%) scale(${element.crop?.scale || 1})`,
            transformOrigin: 'center center',
            display: 'block',
            pointerEvents: 'none',
            userSelect: 'none',
          }}
        />
        {element.expandable && mediaInteractive && <MediaExpandButton onClick={() => onMediaExpand?.(element)} />}
      </div>
    );
  }

  if (element.type === 'text') {
    // A text box with a picture fill shows the photo through its letters: the words
    // are painted transparent and the picture behind them is clipped to the glyphs,
    // so the picture takes the exact shape of what has been typed.
    const masked = hasTextPicture(element) && !editingText;
    const style = element.style || {};
    const justify = style.valign === 'middle' ? 'center' : style.valign === 'bottom' ? 'flex-end' : 'flex-start';
    return (
      <div
        className={`element element-text${animationClass}`}
        style={{
          ...baseStyle,
          background: element.fill && element.fill !== 'transparent' ? element.fill : 'transparent',
          border: element.stroke ? `${element.strokeWidth || 1}px solid ${element.stroke}` : 'none',
          borderRadius: element.radius ? `${element.radius}px` : 0,
          padding: elementPadding(element, 8),
          display: 'flex',
          flexDirection: 'column',
          justifyContent: justify,
          overflow: 'hidden',
          boxSizing: 'border-box',
        }}
      >
        {element.fillImage ? (
          <span className="element-picture-fill" style={pictureFillCss(element.fillImage)} aria-hidden="true" />
        ) : null}
        {editingText ? (
          <div
            key="editor"
            ref={(node) => {
              textAreaRef.current = node;
              if (editorRef) editorRef.current = node;
            }}
            className="inline-text-editor"
            contentEditable
            suppressContentEditableWarning
            spellCheck={false}
            role="textbox"
            aria-multiline="true"
            aria-label="Edit text"
            style={{
              fontFamily: fontStack(style.fontFamily),
              fontSize: `${style.fontSize || 28}px`,
              color: style.color || '#0f172a',
              fontWeight: style.bold ? 700 : 400,
              fontStyle: style.italic ? 'italic' : 'normal',
              textDecoration: style.underline ? 'underline' : 'none',
              textAlign: style.align || 'left',
              lineHeight: style.lineHeight || 1.25,
              letterSpacing: `${style.letterSpacing || 0}px`,
              width: '100%',
              minHeight: '100%',
              background: 'transparent',
              border: 'none',
              outline: 'none',
              padding: 0,
              overflow: 'hidden',
              cursor: 'text',
            }}
            onBlur={() => commitText()}
            onPaste={(event) => {
              const data = event.clipboardData;
              const picture = [...(data?.files || [])].some((item) => String(item.type || '').startsWith('image/'));
              // A picture is not text — leave it to the editor, which drops it on the
              // slide (prevented here so the browser does not also paste it as an image tag).
              if (picture) {
                event.preventDefault();
                return;
              }
              event.preventDefault();
              const html = data?.getData('text/html');
              if (html) {
                const clean = sanitizeHtml(html);
                if (clean && clean !== htmlToPlainText(html)) {
                  document.execCommand('styleWithCSS', false, true);
                  document.execCommand('insertHTML', false, clean);
                  return;
                }
              }
              document.execCommand('insertText', false, data?.getData('text/plain') || '');
            }}
            onKeyDown={(event) => {
              if (event.key === 'Escape') {
                event.preventDefault();
                event.stopPropagation();
                commitText({ cancel: true });
                return;
              }
              if (event.key === 'Enter' && (event.metaKey || event.ctrlKey)) {
                event.preventDefault();
                commitText();
                return;
              }
              // Let Ctrl/Cmd+S reach the editor so the deck can be saved while typing.
              if ((event.ctrlKey || event.metaKey) && event.key.toLowerCase() === 's') return;
              event.stopPropagation();
            }}
          />
        ) : (
          <div
            key="view"
            className={`text-content${masked ? ' text-masked' : ''}`}
            style={{
              fontFamily: fontStack(style.fontFamily),
              fontSize: `${style.fontSize || 28}px`,
              color: masked ? 'transparent' : style.color || '#0f172a',
              fontWeight: style.bold ? 700 : 400,
              fontStyle: style.italic ? 'italic' : 'normal',
              textDecoration: style.underline ? 'underline' : 'none',
              textAlign: style.align || 'left',
              lineHeight: style.lineHeight || 1.25,
              letterSpacing: `${style.letterSpacing || 0}px`,
              whiteSpace: 'pre-wrap',
              wordBreak: 'break-word',
              width: '100%',
              userSelect: 'none',
              ...(masked ? textMaskStyle(element.textImage) : null),
            }}
          >
            {masked ? htmlToPlainText(textElementHtml(element)) : <RichContent element={element} characters={characterAnimation} />}
          </div>
        )}
      </div>
    );
  }
  if (element.type === 'video') {
    // A YouTube/Vimeo link plays through the provider's player; the poster frame
    // stands in until the viewer asks for it. The link is read from `src`, so
    // decks imported before this feature still play.
    const online = parseOnlineVideo(element.src);
    return (
      <div
        className={`element element-video${animationClass}`}
        style={{
          ...baseStyle,
          overflow: 'hidden',
          borderRadius: `${element.radius || 0}px`,
          background: '#020617',
          border: element.stroke ? `${element.strokeWidth || 1}px solid ${element.stroke}` : 'none',
          boxSizing: 'border-box',
        }}
        onClick={(event) => {
          if (!element.expandable || preview) return;
          event.stopPropagation();
          onMediaExpand?.(element);
        }}
      >
        {preview ? (
          <div className="video-preview">
            {element.poster || online?.thumbnailUrl ? (
              <img src={element.poster || online.thumbnailUrl} alt="" draggable={false} />
            ) : (
              <div className="video-preview-fallback" />
            )}
            <span className="video-play-badge">
              <Icon name="play" size={26} filled />
            </span>
            <span className="video-preview-name">{element.name || 'Video'}</span>
          </div>
        ) : online ? (
          <OnlineVideo element={element} playing={onlinePlaying} onPlay={() => setOnlinePlaying(true)} />
        ) : (
          <video
            src={element.src}
            poster={element.poster || undefined}
            controls={element.controls !== false}
            muted={element.muted}
            loop={element.loop}
            autoPlay={element.autoplay}
            playsInline
            preload="metadata"
            style={{ width: '100%', height: '100%', objectFit: element.fit || 'cover', display: 'block' }}
          />
        )}
        {element.expandable && <MediaExpandButton onClick={() => onMediaExpand?.(element)} />}
      </div>
    );
  }

  if (element.type === 'audio') {
    return (
      <div
        className={`element element-audio${animationClass}`}
        style={{
          ...baseStyle,
          borderRadius: `${element.radius || 16}px`,
          background: 'linear-gradient(135deg, rgba(79,70,229,0.95), rgba(14,165,233,0.85))',
          color: '#ffffff',
          display: 'flex',
          alignItems: 'center',
          gap: '12px',
          padding: '14px 16px',
          boxSizing: 'border-box',
          overflow: 'hidden',
        }}
      >
        <span className="audio-icon">
          <Icon name="audio" size={26} />
        </span>
        <span className="audio-meta">
          <span className="audio-label">{element.label || element.name || 'Audio clip'}</span>
          {mediaInteractive && !preview ? (
            <audio src={element.src} controls style={{ width: '100%', height: 28 }} />
          ) : (
            <span className="audio-bars">
              {Array.from({ length: 18 }).map((_, index) => (
                <i key={index} style={{ animationDelay: `${index * 0.08}s` }} />
              ))}
            </span>
          )}
        </span>
        {element.expandable && <MediaExpandButton onClick={() => onMediaExpand?.(element)} />}
      </div>
    );
  }

  if (element.type === 'table') {
    return (
      <div
        className={`element element-table${animationClass}`}
        style={{
          ...baseStyle,
          background: '#ffffff',
          borderRadius: `${element.radius || 2}px`,
          overflow: 'hidden',
          boxShadow: '0 1px 2px rgba(15,23,42,0.08)',
        }}
        onDoubleClick={(event) => {
          if (!onTableDoubleClick) return;
          event.stopPropagation();
          onTableDoubleClick(element);
        }}
      >
        <TableGrid table={element.table} highlight={tableHighlight} />
      </div>
    );
  }

  return null;
}

